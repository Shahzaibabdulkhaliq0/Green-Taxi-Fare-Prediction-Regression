"""Streamlit frontend for the Green Taxi Fare Prediction API."""

import os

import requests
import streamlit as st


# The API URL is configurable so local and AWS deployments use the same app.
API_BASE_URL = os.getenv("API_BASE_URL", "http://localhost:8000").rstrip("/")
PREDICT_URL = f"{API_BASE_URL}/predict"

st.set_page_config(
    page_title="Green Taxi Fare Prediction",
    page_icon="🚕",
    layout="wide",
)

st.title("🚕 Green Taxi Fare Prediction")
st.caption("Enter trip details to estimate the NYC green taxi fare.")
st.info("The estimate is generated by the project's trained ML model. It is not a quoted taxi price.")

with st.form("trip_form"):
    st.subheader("Trip details")

    left, right = st.columns(2)

    with left:
        vendorid = st.selectbox("Vendor ID", options=[1, 2], index=1)
        rate_code = st.selectbox("Rate code", options=list(range(1, 7)), index=0)
        passenger_count = st.number_input(
            "Passenger count", min_value=1, max_value=6, value=1, step=1
        )
        trip_distance = st.number_input(
            "Trip distance (miles)",
            min_value=0.1,
            max_value=50.0,
            value=3.5,
            step=0.1,
        )
        trip_type = st.selectbox("Trip type", options=[1, 2], index=0)

    with right:
        st.markdown("**Pickup location**")
        pickup_longitude = st.number_input(
            "Pickup longitude", min_value=-74.3, max_value=-73.6,
            value=-73.95, step=0.001, format="%.6f"
        )
        pickup_latitude = st.number_input(
            "Pickup latitude", min_value=40.4, max_value=41.0,
            value=40.75, step=0.001, format="%.6f"
        )

        st.markdown("**Dropoff location**")
        dropoff_longitude = st.number_input(
            "Dropoff longitude", min_value=-74.3, max_value=-73.6,
            value=-73.98, step=0.001, format="%.6f"
        )
        dropoff_latitude = st.number_input(
            "Dropoff latitude", min_value=40.4, max_value=41.0,
            value=40.76, step=0.001, format="%.6f"
        )

    st.markdown("**Pickup time**")
    time_col, day_col = st.columns(2)
    with time_col:
        pickup_hour = st.slider("Hour of day", min_value=0, max_value=23, value=14)
    with day_col:
        weekday_names = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]
        pickup_weekday = st.selectbox(
            "Day of week", options=list(range(7)),
            format_func=lambda day: weekday_names[day], index=2
        )

    submitted = st.form_submit_button(
        "Predict fare", type="primary", use_container_width=True
    )

if submitted:
    payload = {
        "vendorid": int(vendorid),
        "rate_code": int(rate_code),
        "Pickup_longitude": float(pickup_longitude),
        "Pickup_latitude": float(pickup_latitude),
        "Dropoff_longitude": float(dropoff_longitude),
        "Dropoff_latitude": float(dropoff_latitude),
        "Passenger_count": int(passenger_count),
        "Trip_distance": float(trip_distance),
        "Trip_type": int(trip_type),
        "pickup_hour": int(pickup_hour),
        "pickup_weekday": int(pickup_weekday),
    }

    try:
        with st.spinner("Requesting prediction from the API..."):
            response = requests.post(PREDICT_URL, json=payload, timeout=30)

        if response.ok:
            result = response.json()
            fare = result.get("predicted_fare")
            currency = result.get("currency", "USD")
            if fare is None:
                st.error("The API response did not contain a predicted fare.")
            else:
                st.success("Prediction completed")
                st.metric("Estimated fare", f"{currency} {float(fare):,.2f}")
        elif response.status_code == 422:
            st.error("The API rejected one or more trip values. Check the input ranges.")
            try:
                st.json(response.json().get("detail", response.json()))
            except ValueError:
                st.write(response.text)
        else:
            st.error(f"Prediction API returned HTTP {response.status_code}.")
            st.code(response.text[:1000])

    except requests.exceptions.ConnectionError:
        st.error("Cannot connect to the prediction API. Check that the API service is running and API_BASE_URL is correct.")
    except requests.exceptions.Timeout:
        st.error("The prediction API did not respond within 30 seconds. Please try again.")
    except requests.exceptions.RequestException as exc:
        st.error(f"Request failed: {exc}")

st.divider()
st.caption("Green Taxi Fare Prediction | Streamlit frontend + FastAPI model-serving API")
